-- Настройки автоматического бэкапа. INSERT OR IGNORE: уже существующие
-- ключи не перезаписываются.
INSERT OR IGNORE INTO system_settings (key, value) VALUES
  -- День недели бэкапа: 0 = воскресенье, 6 = суббота.
  ('backup_weekday', '0'),
  -- Час (0-23 по местному времени), с которого можно делать бэкап.
  ('backup_hour_local', '3'),
  -- Окно в часах — сколько часовых запусков подряд считаются "тем же разом".
  ('backup_window_hours', '2');